import '../utils/formatters.dart';

/// One expense row from the `expenses` table.
class Expense {
  static const List<String> categories = [
    'Food',
    'Transport',
    'Shopping',
    'Bills',
    'Health',
    'Other',
  ];

  static const String fallbackCategory = 'Other';

  final String id;
  final String title;
  final double amount;
  final String category;
  final DateTime date;

  const Expense({
    required this.id,
    required this.title,
    required this.amount,
    required this.category,
    required this.date,
  });

  /// Builds an expense from a database row.
  ///
  /// Defensive on purpose: an unknown category falls back to "Other"
  /// (otherwise the category dropdown would crash), and `amount` is accepted
  /// both as a number and as a string (Postgres `numeric` can arrive as text).
  factory Expense.fromMap(Map<String, dynamic> map) {
    final rawCategory = (map['category'] as String?)?.trim() ?? '';
    final rawAmount = map['amount'];
    final amount = rawAmount is num
        ? rawAmount.toDouble()
        : double.tryParse(rawAmount?.toString() ?? '') ?? 0;

    return Expense(
      id: map['id'].toString(),
      title: (map['title'] as String?)?.trim() ?? '',
      amount: amount,
      category:
          categories.contains(rawCategory) ? rawCategory : fallbackCategory,
      date: DateTime.tryParse(map['date']?.toString() ?? '') ?? DateTime.now(),
    );
  }

  /// Data sent to the database on insert / update.
  /// `id` and `user_id` are generated by the database.
  Map<String, dynamic> toMap() {
    return {
      'title': title,
      'amount': amount,
      'category': category,
      'date': formatDate(date),
    };
  }

  Expense copyWith({
    String? id,
    String? title,
    double? amount,
    String? category,
    DateTime? date,
  }) {
    return Expense(
      id: id ?? this.id,
      title: title ?? this.title,
      amount: amount ?? this.amount,
      category: category ?? this.category,
      date: date ?? this.date,
    );
  }

  /// True when both expenses would store the same data.
  /// Used by the edit form to skip saving when nothing changed.
  bool hasSameContentAs(Expense other) {
    return title == other.title &&
        amount == other.amount &&
        category == other.category &&
        formatDate(date) == formatDate(other.date);
  }
}
